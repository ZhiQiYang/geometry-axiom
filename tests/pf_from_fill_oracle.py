"""C0 acceptance adapter: frozen framing oracle -> real D42/R41 host.

This is test-only. It reuses the existing core probe's D7 declarations and
dependency order, then replaces its ordinary surface and EXPLICIT grid with
a panel fill, a derived placement, and live ``from-fill`` references. It is
not a production framing recipe, a PF-6 implementation, or a new field rule.

F3/F4 are the deliberately bounded witness: all eight layouts in each room,
592 members. Pending roles, forced cycles, ``through`` fallbacks, relocated
seams, and unsupported mark adjustments fail closed. F5's two unresolved
hole-perpendicular roles are reported explicitly, never silently promoted.
"""

from __future__ import annotations

import argparse
from collections import Counter
from functools import lru_cache
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tests._bridge import BridgeSession
from tests import test_panel_fill_layout as pf2

FRAMING = ROOT / "geometry-core" / "framing-template"
GOLDEN = FRAMING / "oracle" / "oracle-golden.json"
ROOMS = ("F3次臥", "F4走道")
HOST, FILL, GRID = 10, 1, 11
FINISH_Z, THICKNESS, DEPTH = 2500, 6, 33


def _require(condition, message):
    if not condition:
        raise AssertionError("C0_ORACLE: " + message)


def _module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@lru_cache(maxsize=1)
def _tools():
    return (_module("c0_framing_probe", FRAMING / "core-probe" / "gen_scenes.py"),
            _module("c0_framing_oracle", FRAMING / "oracle" / "framing_oracle.py"))


def _label(member):
    # Same published label contract as make_golden.kind_label; geometry is
    # regenerated by framing_oracle and independently measured from D7 below.
    if member["kind"] == "rc_parallel" and member.get("core_role") == "custom":
        return "rc_parallel:custom"
    label = "secondary:" + member["role"] if member["kind"] == "secondary" else member["kind"]
    return label + (":custom%d" % member["priority"] if member.get("core_role") == "custom" else "")


def validate_probe_scene(scene):
    """Do not inherit gen_scenes' diagnostic-only fallback behaviours."""
    _require(not scene.cycles, f"{scene.room}/{scene.layout}: forced dependency cycle")
    pending = [(m.golden, m.pending) for m in scene.members if m.pending]
    _require(not scene.pending and not pending,
             f"{scene.room}/{scene.layout}: pending roles {pending}")
    _require(not scene.over_cap, f"{scene.room}/{scene.layout}: native timber capacity")
    fallback = [(m.golden, m.span_note) for m in scene.members if m.span[0] != "between"]
    _require(not fallback, f"{scene.room}/{scene.layout}: through fallback {fallback}")


def _index(plan, axis, coordinate):
    delta = coordinate - plan["base"][axis]
    pitch = plan["panel"][axis] + plan["params"]["gap"]
    _require(delta % pitch == 0,
             f"{plan['scene'].room}/{plan['scene'].layout}: relocated seam {axis}={coordinate}")
    return delta // pitch


def _mark_sources(plan, oracle, result):
    """Retain the oracle's jig anchor, rather than copying its EXPLICIT list.

    The witness needs only integral multiples of the accepted M=367 jig.
    Where the room has no board-end seam, the offscreen lattice line next to
    the starting wall plus the half-gap reconstructs that wall's coordinate.
    All guide expressions therefore retain a live fill source as well.
    """
    a = 0 if plan["layout"]["A"] == "x" else 1
    b = 1 - a
    axis = "uv"[b]
    low, high = plan["bounds"][b], plan["bounds"][b + 2]
    start_low = plan["layout"]["b_start"] == "min"
    p = plan["params"]
    width, jig, gap = p["w"], p["M"], p["gap"]
    bounds = [(low, "rc")] + [(s, "seam") for s in sorted(result["seams_b"])] + [(high, "rc")]
    marks = {}
    for (c0, k0), (c1, k1) in zip(bounds, bounds[1:]):
        if k0 == k1 == "seam":
            anchor = c0 if start_low else c1
        elif k0 == "seam":
            anchor = c0
        elif k1 == "seam":
            anchor = c1
        else:
            anchor = c0 if start_low else c1
        wall_anchor = k0 == k1 == "rc"
        index = (-1 if start_low else 0) if wall_anchor else _index(plan, b, anchor)
        base = f"grid:{GRID}:{axis}:{index}"
        if wall_anchor:
            base += ("+spec:c0_upper_gap" if start_low else "-spec:c0_lower_gap")
        for coordinate in oracle.jig_marks(c0, k0, c1, k1, start_low, jig,
                                           width, width // 2, width - width // 2):
            distance = coordinate - anchor
            _require(distance % jig == 0,
                     "adjusted jig step outside the C0 F3/F4 witness")
            steps = distance // jig
            expression = base + ("+" if steps > 0 else "-") + f"{abs(steps)}*spec:c0_jig"
            _require(coordinate not in marks, "ambiguous jig provenance")
            marks[coordinate] = dict(axis=axis, index=str(index), expression=expression,
                                     jigAnchor=anchor, jigSteps=steps, wallAnchor=wall_anchor,
                                     offset=coordinate - (plan["base"][b] + index * (plan["panel"][b] + gap)))
    return marks


def plan_oracle_cases(rooms=ROOMS):
    """Validate frozen answers and construct source-preserving native plans."""
    probe, oracle = _tools()
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    selected = {name: golden["rooms"][name] for name in rooms}
    built = probe.build(dict(params=golden["params"], rooms=selected))
    _require(not built.skipped and not built.disagreements,
             f"probe skipped/disagreements: {built.skipped!r}/{built.disagreements!r}")
    plans = []
    for scene in built.scenes:
        validate_probe_scene(scene)
        room = selected[scene.room]
        frozen = room["layouts"][scene.layout]
        params = dict(golden["params"], **room["room"].get("params", {}))
        layout = frozen["layout"]
        result = oracle.build(room["room"], layout, params)
        failures = oracle.check(result, params)
        verdict, problems = oracle.verdict(result, params, failures)
        _require(verdict == "buildable" and not failures and not problems,
                 f"oracle verdict {scene.room}/{scene.layout}: {verdict}/{failures}/{problems}")
        regenerated = sorted([_label(m), list(m["rect"])] for m in result["timbers"])
        _require(regenerated == frozen["timbers"], "current oracle differs from frozen per-member answers")
        _require(sorted(result["seams_a"]) == frozen["seams_a"] and
                 sorted(result["seams_b"]) == frozen["seams_b"], "current oracle differs from frozen seam answers")
        outer = room["room"]["outer"]
        bounds = [min(p[0] for p in outer), min(p[1] for p in outer),
                  max(p[0] for p in outer), max(p[1] for p in outer)]
        a = 0 if layout["A"] == "x" else 1
        b = 1 - a
        panel, starts = [0, 0], [None, None]
        panel[a], panel[b] = params["P"], params["L"]
        starts[a], starts[b] = layout["a_start"], layout["b_start"]
        origin = [bounds[i] if starts[i] == "min" else bounds[i + 2] - panel[i] for i in (0, 1)]
        plan = dict(scene=scene, room=room["room"], params=params, layout=layout,
                    bounds=bounds, panel=panel, origin=origin,
                    base=[origin[i] + panel[i] + params["gap"] // 2 for i in (0, 1)],
                    mainAlong="uv"[b], sources={}, guides=[])
        plan["seams"] = {"uv"[axis]: {str(_index(plan, axis, c)): c for c in result[key]}
                         for axis, key in ((a, "seams_a"), (b, "seams_b"))}
        marks = _mark_sources(plan, oracle, result)
        guide_ids = {}
        for member in sorted(scene.members, key=lambda m: m.id):
            if member.edge is not None:
                source = dict(kind="edge", ref=member.edge.ref)
            elif member.kind in ("main", "secondary:seam"):
                axis = "uv".index(member.grid_axis)
                index = _index(plan, axis, member._center)
                _require(str(index) in plan["seams"][member.grid_axis], "member is not on an oracle seam")
                source = dict(kind="grid", axis=member.grid_axis, index=str(index))
            elif member.kind == "secondary:mark":
                _require(member._center in marks, "member has no accepted jig provenance")
                mark = marks[member._center]
                _require(mark["axis"] == member.grid_axis, "mark axis mismatch")
                if member._center not in guide_ids:
                    identifier = len(guide_ids) + 1
                    guide_ids[member._center] = identifier
                    plan["guides"].append(dict(id=identifier, coordinate=member._center, **mark))
                source = dict(kind="guide", id=guide_ids[member._center], **mark)
            else:
                raise AssertionError("C0_ORACLE: unsupported native mapping " + member.kind)
            plan["sources"][member.id] = source
        plans.append(plan)
    return plans


def deferred_cases():
    """Expose the existing F5 policy gap without executing its provisional roles."""
    probe, _ = _tools()
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    built = probe.build(dict(params=golden["params"], rooms={"F5廚房": golden["rooms"]["F5廚房"]}))
    scene = next(s for s in built.scenes if s.layout == 0)
    try:
        validate_probe_scene(scene)
    except AssertionError as error:
        return [dict(room=scene.room, layout=scene.layout, name=scene.name,
                     members=len(scene.members), status="deferred", reason=str(error),
                     pending=[dict(golden=m.golden, kind=m.kind, rect=list(m.rect), reason=m.pending)
                              for m in scene.members if m.pending])]
    raise AssertionError("C0_ORACLE: F5 policy status changed; review the witness scope explicitly")


def _key(value):
    return "key-hex:" + json.dumps(value, separators=(",", ":")).encode("utf-8").hex()


def _edges(plan, host):
    """Bind each probe boundary to the complete, native R41 provenance key."""
    native = [e for c in host["derived"]["components"] for e in c["edges"]]
    probe, _ = _tools()
    result = {}
    for edge in probe.room_edges(dict(room=plan["room"])):
        endpoints = {(edge.x0, edge.y0), (edge.x1, edge.y1)}
        hits = [e for e in native if {tuple(e["start"]), tuple(e["end"])} == endpoints]
        _require(len(hits) == 1, "missing or ambiguous native derived-host edge " + edge.ref)
        _require(hits[0]["key"], "empty native derived-host key")
        result[edge.ref] = _key(hits[0]["key"])
    return result


def footprint(geometry):
    """Independent world XY envelope of the four actual D7 footprint corners."""
    origin, (direction, cross, _) = geometry["origin"], geometry["axes"]
    points = [(origin[0] + along * direction[0] + across * cross[0],
               origin[1] + along * direction[1] + across * cross[1])
              for along in (0, geometry["length"]) for across in (0, geometry["A"])]
    return [min(p[0] for p in points), min(p[1] for p in points),
            max(p[0] for p in points), max(p[1] for p in points)]


def _measure(plan, references, declarations):
    scene = plan["scene"]
    timbers = {t["id"]: t for t in references["timbers"]}
    _require(set(timbers) == {m.id for m in scene.members}, "native membership differs from oracle")
    grids = references["grids"]
    _require(len(grids) == 1 and grids[0]["id"] == GRID and
             grids[0].get("fillId") == FILL and grids[0].get("indexSpace") == "lattice",
             "the actual source must be the single live from-fill lattice")
    guides = {g["id"]: g for g in references["guides"]}
    _require(set(guides) == {g["id"] for g in plan["guides"]}, "native jig guide membership")
    for guide in plan["guides"]:
        actual = guides[guide["id"]]
        _require(actual["off"] == guide["coordinate"] and actual["surface"] == HOST and
                 actual["expression"] == guide["expression"], "native jig guide source/coordinate")
    rows = []
    for member in sorted(scene.members, key=lambda m: m.golden):
        timber = timbers[member.id]
        geometry = timber.get("geometry")
        _require(geometry is not None, f"unplaced native member {member.id}")
        rectangle = footprint(geometry)
        _require(rectangle == list(member.rect),
                 f"{scene.room}/{scene.layout}/golden {member.golden}: {rectangle} != {member.rect}")
        _require(geometry["surface"] == HOST and geometry["A"] == plan["params"]["w"] and
                 geometry["B"] == DEPTH and geometry["origin"][2] == FINISH_Z + THICKNESS and
                 geometry["axes"][2] == [0, 0, 1], "actual D42 host/section/depth differs")
        priority = member.priority or {"boundary": 1, "primary": 2, "secondary": 3}[member.role]
        _require(timber["role"] == member.role and timber["definition"]["priority"] == priority,
                 "native role or priority differs from approved probe mapping")
        anchor, selector = declarations[member.id]
        _require(timber["definition"]["anchor"] == anchor and
                 timber["definition"]["selector"] == selector, "native D7 source identity was lost")
        rows.append(dict(golden=member.golden, id=member.id, kind=member.kind,
                         role=member.role, priority=priority, source=plan["sources"][member.id],
                         anchor=anchor, selector=selector, expected=list(member.rect), native=rectangle,
                         geometry=geometry, matchesOracle=True))
    return rows


def run_oracle_cases(case, *, rooms=ROOMS, cold=True):
    """Run every requested case using the caller's fresh, explicitly selected bridge.

    ``case`` supplies the existing PF test plumbing (seed/apply/read/command/
    directory/binary). The returned JSON-ready record contains every member,
    its native measured geometry, serialized source, and cold-process result.
    """
    plans = plan_oracle_cases(rooms)
    records = []
    for plan in plans:
        scene, p = plan["scene"], plan["params"]
        outline = " ".join(f"{u},{v}" for u, v in plan["room"]["outer"])
        for hole in plan["room"].get("holes", []):
            outline += " hole " + " ".join(f"{u},{v}" for u, v in hole)
        case.seed(width=p["P"], length=p["L"], thickness=str(THICKNESS), outline=outline, obstacles=[])
        case.apply([pf2.put(pf2.surface(boundary=8, origin=(0, 0, FINISH_Z), obstacles=[])),
                    pf2.fill(origin=plan["origin"], gap=p["gap"], lengthAlong=plan["mainAlong"]),
                    dict(op="put-derived-placement", value=dict(id=HOST, fillId=FILL, h=DEPTH))])
        host = case.read()["state"]["derivedPlacements"][0]
        _require(host["id"] == HOST and host["definition"]["fillId"] == FILL, "missing true derived host")
        keys = _edges(plan, host)
        commands = []

        def commit(line):
            commands.append(line)
            reply = case.command("line " + line)
            _require(reply["ok"], f"{scene.room}/{scene.layout}: {line}: {reply}")

        commit(f"grid {GRID} on {HOST} from-fill {FILL} main-along {plan['mainAlong']}")
        commit(f"spec c0_jig {p['M']}")
        if any(g["wallAnchor"] for g in plan["guides"]):
            commit(f"spec c0_lower_gap {p['gap'] // 2}")
            commit(f"spec c0_upper_gap {p['gap'] - p['gap'] // 2}")
        for guide in plan["guides"]:
            along = "v" if guide["axis"] == "u" else "u"
            commit(f"guide {guide['id']} {HOST} {along} {guide['expression']}")
        query = case.command(f"grid-query grid {GRID} rect " + " ".join(map(str, plan["bounds"])) + " mode exact limit 64")
        _require(query["ok"] and query["exact"], "exact from-fill seam query failed")
        for axis in "uv":
            got = {row["index"]: row["coordinate"] for row in query["axes"][axis]["lines"]}
            _require(got == plan["seams"][axis], f"signed {axis} source identity: {got} != {plan['seams'][axis]}")
        declarations = {}
        for member in sorted(scene.members, key=lambda m: m.id):
            source = plan["sources"][member.id]
            if source["kind"] == "edge":
                anchor = "at-face " + keys[source["ref"]]
            elif source["kind"] == "grid":
                anchor = f"at-line grid {GRID} {source['axis']} {source['index']}"
            else:
                anchor = f"at-line guide {source['id']}"
            selector = "between " + " ".join(keys.get(ref, ref) for ref in member.span[1:])
            _require(all(ref.startswith(("t", "key-hex:")) for ref in selector.split()[1:]),
                     "raw ordinal edge in a derived-host declaration")
            declarations[member.id] = (anchor, selector)
            priority = f" priority {member.priority}" if member.role == "custom" else ""
            commit(f"timber {member.id} {p['w']} {DEPTH} role {member.role}{priority}")
            commit(f"place {member.id} on {HOST} {anchor} {selector} {member.direction} +n")
        references = case.command("references")
        _require(references["ok"], "native references failed")
        rows = _measure(plan, references, declarations)
        state = case.read()["state"]
        serialized = case.command("dump")["text"]
        _require(f"grid {GRID} on {HOST} from-fill {FILL}" in serialized,
                 "save replaced the live source with sampled coordinates")
        _require(not any(line.startswith(("surface ", "placement ")) for line in serialized.splitlines()),
                 "the witness must not introduce an ordinary placement")
        if cold:
            path = case.directory / "c0-oracle-cold.scene"
            path.write_bytes(serialized.encode("utf-8"))
            with BridgeSession(case.binary, cwd=case.directory) as reopened:
                loaded = reopened.command("loadfile " + str(path))
                _require(loaded["ok"], f"cold process load: {loaded}")
                cold_rows = _measure(plan, reopened.command("references"), declarations)
                _require(reopened.command("panel-fill-read")["state"] == state,
                         "cold process changed native panel-fill state")
                _require(reopened.command("dump")["text"] == serialized,
                         "cold process changed saved source bytes")
            for row, cold_row in zip(rows, cold_rows):
                row["cold"] = cold_row["native"]
        records.append(dict(room=scene.room, layout=scene.layout, name=scene.name,
                            members=len(rows), sourceCounts=dict(Counter(s["kind"] for s in plan["sources"].values())),
                            origin=plan["origin"], signedSeams=plan["seams"],
                            coldVerified=cold, rows=rows, commands=commands,
                            dumpSha256=hashlib.sha256(serialized.encode()).hexdigest(), serializedScene=serialized))
    paths = [GOLDEN, FRAMING / "oracle" / "framing_oracle.py", FRAMING / "core-probe" / "gen_scenes.py"]
    return dict(schema="c0-from-fill-oracle/1", cases=records,
                caseCount=len(records), memberCount=sum(r["members"] for r in records),
                bridgeSha256=hashlib.sha256(Path(case.binary).read_bytes()).hexdigest(),
                sourceHashes={str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths},
                deferred=deferred_cases())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bridge", required=True, help="explicit freshly built bridge; no automatic rebuild")
    parser.add_argument("--output", type=Path, help="JSON evidence path; defaults to stdout")
    args = parser.parse_args()
    case = pf2.PanelFillLayout()
    case.binary = str(Path(args.bridge).resolve())
    case.setUp()
    try:
        evidence = run_oracle_cases(case)
    finally:
        case.doCleanups()
    text = json.dumps(evidence, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.write_text(text, encoding="utf-8", newline="\n")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
